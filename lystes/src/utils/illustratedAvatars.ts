/**
 * Simple hash function for deterministic selection
 */
function hashCode(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash;
  }
  return Math.abs(hash);
}

/**
 * Get a deterministic illustrated avatar based on seed and gender
 */
export function getIllustratedAvatar(
  seed: string,
  gender: "female" | "male"
): string {
  const avatars = gender === "female" ? ILLUSTRATED_AVATARS.women : ILLUSTRATED_AVATARS.men;
  const hash = hashCode(seed);
  const index = hash % avatars.length;
  return avatars[index];
}

/**
 * Get avatar for a named team member, or generate one if not found
 */
export function getTeamMemberAvatar(
  name: string,
  gender: "female" | "male" = "female"
): string {
  const normalizedName = name.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  return TEAM_AVATARS[normalizedName] || getIllustratedAvatar(name, gender);
}
